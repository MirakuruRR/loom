bool FLoomApplier::Apply(const TSharedRef<FJsonObject>& Doc)
{
	int32 Version = -1;
	if (!Doc->TryGetNumberField(TEXT("version"), Version) || Version != 0)
	{
		Report->SetStringField(TEXT("error"), TEXT("ops.json must have \"version\": 0"));
		return false;
	}
	const TArray<TSharedPtr<FJsonValue>>* Ops = nullptr;
	if (!Doc->TryGetArrayField(TEXT("ops"), Ops))
	{
		Report->SetStringField(TEXT("error"), TEXT("ops.json has no \"ops\" array"));
		return false;
	}

	TArray<TSharedPtr<FJsonValue>> Outcomes;
	bool bOk = true;
	for (int32 Index = 0; Index < Ops->Num(); ++Index)
	{
		const TSharedPtr<FJsonObject>* Op = nullptr;
		FString Error;
		FString Name = TEXT("?");
		if (!(*Ops)[Index]->TryGetObject(Op))
		{
			Error = TEXT("op is not an object");
		}
		else
		{
			(*Op)->TryGetStringField(TEXT("op"), Name);
			ApplyOp(Op->ToSharedRef(), Error);
		}

		TSharedRef<FJsonObject> Outcome = MakeShared<FJsonObject>();
		Outcome->SetNumberField(TEXT("index"), Index);
		Outcome->SetStringField(TEXT("op"), Name);
		Outcome->SetBoolField(TEXT("ok"), Error.IsEmpty());
		if (!Error.IsEmpty())
		{
			Outcome->SetStringField(TEXT("error"), Error);
			UE_LOG(LogLoom, Error, TEXT("Loom: op %d (%s): %s"), Index, *Name, *Error);
			bOk = false;
		}
		Outcomes.Add(MakeShared<FJsonValueObject>(Outcome));
		if (!bOk)
		{
			break;
		}
	}
	Report->SetArrayField(TEXT("ops"), Outcomes);
	ExportGraphs();
	return bOk;
}

bool FLoomApplier::ApplyOp(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	const FString Name = Op->GetStringField(TEXT("op"));
	if (Name == TEXT("blueprint"))
	{
		return OpBlueprint(Op, OutError);
	}
	if (Name == TEXT("enum"))
	{
		return OpEnum(Op, OutError);
	}
	if (Name == TEXT("struct"))
	{
		return OpStruct(Op, OutError);
	}
	if (Enum || Struct)
	{
		if (Name == TEXT("save"))
		{
			return OpSave(OutError);
		}
		OutError = TEXT("a document that makes an enum or a struct holds that op and \"save\", and no other");
		return false;
	}
	if (!Blueprint)
	{
		OutError = TEXT("the first op must be \"blueprint\", \"enum\" or \"struct\"");
		return false;
	}
	if (Name == TEXT("implement")) return OpImplement(Op, OutError);
	if (Name == TEXT("variable")) return OpVariable(Op, OutError);
	if (Name == TEXT("dispatcher")) return OpDispatcher(Op, OutError);
	if (Name == TEXT("component")) return OpComponent(Op, OutError);
	if (Name == TEXT("widget")) return OpWidget(Op, OutError);
	if (Name == TEXT("function")) return OpFunction(Op, OutError);
	if (Name == TEXT("node")) return OpNode(Op, OutError);
	if (Name == TEXT("link")) return OpLink(Op, OutError);
	if (Name == TEXT("default")) return OpDefault(Op, OutError);
	if (Name == TEXT("compile")) return OpCompile(OutError);
	if (Name == TEXT("class_default")) return OpClassDefault(Op, OutError);
	if (Name == TEXT("save")) return OpSave(OutError);
	OutError = FString::Printf(TEXT("unknown op '%s'"), *Name);
	return false;
}

bool FLoomApplier::OpBlueprint(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	if (Blueprint || Enum || Struct)
	{
		OutError = TEXT("one ops.json builds one Blueprint");
		return false;
	}
	const FString PackagePath = Op->GetStringField(TEXT("path"));
	const FString ParentPath = Op->GetStringField(TEXT("parent"));
	FString Source;
	Op->TryGetStringField(TEXT("source"), Source);
	bool bWidget = false;
	Op->TryGetBoolField(TEXT("widget"), bWidget);
	FString CanvasName;
	if (bWidget && !Op->TryGetStringField(TEXT("canvas"), CanvasName))
	{
		OutError = TEXT("a widget Blueprint's op names its canvas");
		return false;
	}

	FText Reason;
	if (!FPackageName::IsValidLongPackageName(PackagePath, false, &Reason))
	{
		OutError = FString::Printf(TEXT("bad path %s: %s"), *PackagePath, *Reason.ToString());
		return false;
	}
	UClass* Parent = LoadObject<UClass>(nullptr, *ParentPath);
	if (!Parent)
	{
		OutError = FString::Printf(TEXT("no parent class %s"), *ParentPath);
		return false;
	}
	const FString AssetName = FPackageName::GetLongPackageAssetName(PackagePath);

	if (FPackageName::DoesPackageExist(PackagePath))
	{
		Blueprint = LoadObject<UBlueprint>(nullptr, *(PackagePath + TEXT(".") + AssetName));
		if (!Blueprint)
		{
			OutError = FString::Printf(TEXT("%s exists and is not a Blueprint"), *PackagePath);
			return false;
		}
		if (!Blueprint->BlueprintDescription.StartsWith(GeneratedTag))
		{
			OutError = FString::Printf(TEXT("%s was not made by loom; refusing to overwrite it"), *PackagePath);
			Blueprint = nullptr;
			return false;
		}
		if (Blueprint->IsA<UWidgetBlueprint>() != bWidget)
		{
			OutError = FString::Printf(TEXT("%s %s a widget Blueprint, and the ops say otherwise"), *PackagePath,
				bWidget ? TEXT("is not") : TEXT("is"));
			Blueprint = nullptr;
			return false;
		}
		if (Blueprint->ParentClass != Parent)
		{
			OutError = FString::Printf(TEXT("%s has parent %s, not %s"), *PackagePath,
				*GetPathNameSafe(Blueprint->ParentClass), *ParentPath);
			Blueprint = nullptr;
			return false;
		}
		// Start from nothing each time: ops.json describes the whole Blueprint.
		FBlueprintEditorUtils::RemoveGraphs(Blueprint, TArray<UEdGraph*>(Blueprint->FunctionGraphs));
		FBlueprintEditorUtils::RemoveGraphs(Blueprint, TArray<UEdGraph*>(Blueprint->DelegateSignatureGraphs));
		// The interfaces too, with the graphs made for their functions, so one the source no longer
		// implements goes, and each it does is implemented again from nothing.
		for (const FBPInterfaceDescription& Interface : TArray<FBPInterfaceDescription>(Blueprint->ImplementedInterfaces))
		{
			FBlueprintEditorUtils::RemoveGraphs(Blueprint, Interface.Graphs);
		}
		Blueprint->ImplementedInterfaces.Empty();
		if (USimpleConstructionScript* Construction = Blueprint->SimpleConstructionScript)
		{
			for (USCS_Node* Node : TArray<USCS_Node*>(Construction->GetAllNodes()))
			{
				if (Node != Construction->GetDefaultSceneRootNode())
				{
					Construction->RemoveNodeAndPromoteChildren(Node);
				}
			}
		}
		TArray<FName> Vars;
		for (const FBPVariableDescription& Var : Blueprint->NewVariables)
		{
			Vars.Add(Var.VarName);
		}
		FBlueprintEditorUtils::BulkRemoveMemberVariables(Blueprint, Vars);
	}
	else
	{
		UPackage* Package = CreatePackage(*PackagePath);
		Blueprint = bWidget
			? FKismetEditorUtilities::CreateBlueprint(Parent, Package, FName(AssetName), BPTYPE_Normal,
				UWidgetBlueprint::StaticClass(), UWidgetBlueprintGeneratedClass::StaticClass())
			: FKismetEditorUtilities::CreateBlueprint(Parent, Package, FName(AssetName),
				// A function library's functions compile as static, with a world context the
				// compiler supplies. An interface's functions are signatures only.
				Parent->IsChildOf<UBlueprintFunctionLibrary>() ? BPTYPE_FunctionLibrary
					: Parent == UInterface::StaticClass() ? BPTYPE_Interface
					: BPTYPE_Normal,
				UBlueprint::StaticClass(), UBlueprintGeneratedClass::StaticClass());
		if (!Blueprint)
		{
			OutError = FString::Printf(TEXT("could not create a Blueprint at %s"), *PackagePath);
			return false;
		}
		FAssetRegistryModule::AssetCreated(Blueprint);
	}

	// A new Blueprint comes with placeholder event nodes, and an old one with our last build's.
	for (UEdGraph* Graph : Blueprint->UbergraphPages)
	{
		for (UEdGraphNode* Node : TArray<UEdGraphNode*>(Graph->Nodes))
		{
			Graph->RemoveNode(Node);
		}
	}
	if (UWidgetBlueprint* WidgetBlueprint = Cast<UWidgetBlueprint>(Blueprint))
	{
		// The tree is rebuilt from the ops too. The old widgets are moved out of the way first,
		// since a new widget cannot take the name of one still in the tree's package.
		TArray<UWidget*> Old;
		WidgetBlueprint->WidgetTree->GetAllWidgets(Old);
		for (UWidget* Widget : Old)
		{
			WidgetBlueprint->OnVariableRemoved(Widget->GetFName());
			Widget->Rename(nullptr, GetTransientPackage(), REN_DontCreateRedirectors);
		}
		// The compiler names it, as it names everything of its own, so no widget of the source's
		// can take its name.
		UCanvasPanel* Root = WidgetBlueprint->WidgetTree->ConstructWidget<UCanvasPanel>(UCanvasPanel::StaticClass(), FName(CanvasName));
		WidgetBlueprint->WidgetTree->RootWidget = Root;
	}
	Blueprint->BlueprintDescription = Source.IsEmpty()
		? FString(GeneratedTag)
		: FString::Printf(TEXT("%s Source: %s"), GeneratedTag, *Source);
	FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Blueprint);
	return true;
}

bool FLoomApplier::OpEnum(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	if (Blueprint || Enum || Struct)
	{
		OutError = TEXT("an enum is made by an ops.json of its own");
		return false;
	}
	const FString PackagePath = Op->GetStringField(TEXT("path"));
	FString Source;
	Op->TryGetStringField(TEXT("source"), Source);
	FString Description;
	Op->TryGetStringField(TEXT("description"), Description);
	const TArray<TSharedPtr<FJsonValue>>* Values = nullptr;
	if (!Op->TryGetArrayField(TEXT("values"), Values) || Values->IsEmpty())
	{
		OutError = TEXT("an enum has at least one value");
		return false;
	}

	FText Reason;
	if (!FPackageName::IsValidLongPackageName(PackagePath, false, &Reason))
	{
		OutError = FString::Printf(TEXT("bad path %s: %s"), *PackagePath, *Reason.ToString());
		return false;
	}
	const FString AssetName = FPackageName::GetLongPackageAssetName(PackagePath);
	const FString Tag = Source.IsEmpty() ? FString(GeneratedTag) : FString::Printf(TEXT("%s Source: %s"), GeneratedTag, *Source);
	UUserDefinedEnum* Made = nullptr;
	if (FPackageName::DoesPackageExist(PackagePath))
	{
		Made = LoadObject<UUserDefinedEnum>(nullptr, *(PackagePath + TEXT(".") + AssetName));
		if (!Made)
		{
			OutError = FString::Printf(TEXT("%s exists and is not an enum"), *PackagePath);
			return false;
		}
		const FString* Generated = Made->GetPackage()->GetMetaData().FindValue(Made, GeneratedKey);
		if (!Generated || !Generated->StartsWith(GeneratedTag))
		{
			OutError = FString::Printf(TEXT("%s was not made by loom; refusing to overwrite it"), *PackagePath);
			return false;
		}
	}
	else
	{
		UPackage* Package = CreatePackage(*PackagePath);
		Made = Cast<UUserDefinedEnum>(FEnumEditorUtils::CreateUserDefinedEnum(Package, FName(AssetName), RF_Public | RF_Standalone | RF_Transactional));
		if (!Made)
		{
			OutError = FString::Printf(TEXT("could not create an enum at %s"), *PackagePath);
			return false;
		}
		FAssetRegistryModule::AssetCreated(Made);
	}

	// Blueprints hold a value by its place in the list, so a value that moves or goes is removed
	// and moved as the enum editor does it, which also moves the places already held in memory.
	// The values keep the names the source gives them rather than the editor's NewEnumerator0 and
	// so on, since Blueprints name a value by that.
	TArray<FString> Wanted;
	for (const TSharedPtr<FJsonValue>& Value : *Values)
	{
		Wanted.Add(Value->AsObject()->GetStringField(TEXT("name")));
	}
	const auto Current = [Made]()
	{
		TArray<FString> Names;
		// The last entry is the generated _MAX.
		for (int32 Index = 0; Index < Made->NumEnums() - 1; ++Index)
		{
			Names.Add(Made->GetNameStringByIndex(Index));
		}
		return Names;
	};
	for (int32 Index = Current().Num() - 1; Index >= 0; --Index)
	{
		if (!Wanted.Contains(Current()[Index]))
		{
			FEnumEditorUtils::RemoveEnumeratorFromUserDefinedEnum(Made, Index);
		}
	}
	// A new value goes at the end first, where it moves no other.
	FEnumEditorUtils::FEnumEditorManager::Get().PreChange(Made, FEnumEditorUtils::Changed);
	Made->Modify();
	TArray<TPair<FName, int64>> Names;
	for (const FString& Name : Current())
	{
		Names.Emplace(*Made->GenerateFullEnumName(*Name), Names.Num());
	}
	for (const FString& Name : Wanted)
	{
		if (!Current().Contains(Name))
		{
			Names.Emplace(*Made->GenerateFullEnumName(*Name), Names.Num());
		}
	}
#if ENGINE_MAJOR_VERSION > 5 || (ENGINE_MAJOR_VERSION == 5 && ENGINE_MINOR_VERSION >= 8)
	// 5.8 takes every argument. A byte, as the editor makes a user defined enum.
	Made->SetEnums(Names, UEnum::ECppForm::Namespaced, UEnum::EUnderlyingType::uint8, EEnumFlags::None, UEnum::EAddMaxKeyIfMissing::Yes);
#else
	Made->SetEnums(Names, UEnum::ECppForm::Namespaced);
#endif
	for (int32 Index = 0; Index < Wanted.Num(); ++Index)
	{
		const int32 At = Current().IndexOfByKey(Wanted[Index]);
		if (At != Index)
		{
			FEnumEditorUtils::MoveEnumeratorInUserDefinedEnum(Made, At, Index);
		}
	}
	Made->DisplayNameMap.Empty();
	for (int32 Index = 0; Index < Values->Num(); ++Index)
	{
		const TSharedPtr<FJsonObject>& Value = (*Values)[Index]->AsObject();
		FString Label = Value->GetStringField(TEXT("name"));
		Value->TryGetStringField(TEXT("label"), Label);
		Made->DisplayNameMap.Add(FName(*Made->GetNameStringByIndex(Index)), FText::AsCultureInvariant(Label));
		FString Tooltip;
		if (Value->TryGetStringField(TEXT("description"), Tooltip))
		{
			Made->SetMetaData(TEXT("ToolTip"), *Tooltip, Index);
		}
		else
		{
			Made->RemoveMetaData(TEXT("ToolTip"), Index);
		}
	}
	Made->EnumDescription = FText::AsCultureInvariant(Description);
	Made->GetPackage()->GetMetaData().SetValue(Made, GeneratedKey, *Tag);
	// As the editor finishes an undone change to an enum: the nodes and pins that use it are
	// brought up to date, and whatever listens is told.
	FEnumEditorUtils::PostEditUndo(Made);
	Enum = Made;
	return true;
}

bool FLoomApplier::OpStruct(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	if (Blueprint || Enum || Struct)
	{
		OutError = TEXT("a struct is made by an ops.json of its own");
		return false;
	}
	const FString PackagePath = Op->GetStringField(TEXT("path"));
	FString Source;
	Op->TryGetStringField(TEXT("source"), Source);
	FString Description;
	Op->TryGetStringField(TEXT("description"), Description);
	const TArray<TSharedPtr<FJsonValue>>* Fields = nullptr;
	if (!Op->TryGetArrayField(TEXT("fields"), Fields) || Fields->IsEmpty())
	{
		OutError = TEXT("a struct has at least one field");
		return false;
	}

	FText Reason;
	if (!FPackageName::IsValidLongPackageName(PackagePath, false, &Reason))
	{
		OutError = FString::Printf(TEXT("bad path %s: %s"), *PackagePath, *Reason.ToString());
		return false;
	}
	const FString AssetName = FPackageName::GetLongPackageAssetName(PackagePath);
	const FString Tag = Source.IsEmpty() ? FString(GeneratedTag) : FString::Printf(TEXT("%s Source: %s"), GeneratedTag, *Source);
	UUserDefinedStruct* Made = nullptr;
	if (FPackageName::DoesPackageExist(PackagePath))
	{
		Made = LoadObject<UUserDefinedStruct>(nullptr, *(PackagePath + TEXT(".") + AssetName));
		if (!Made)
		{
			OutError = FString::Printf(TEXT("%s exists and is not a struct"), *PackagePath);
			return false;
		}
		const FString* Generated = Made->GetPackage()->GetMetaData().FindValue(Made, GeneratedKey);
		if (!Generated || !Generated->StartsWith(GeneratedTag))
		{
			OutError = FString::Printf(TEXT("%s was not made by loom; refusing to overwrite it"), *PackagePath);
			return false;
		}
	}
	else
	{
		UPackage* Package = CreatePackage(*PackagePath);
		Made = FStructureEditorUtils::CreateUserDefinedStruct(Package, FName(AssetName), RF_Public | RF_Standalone | RF_Transactional);
		if (!Made)
		{
			OutError = FString::Printf(TEXT("could not create a struct at %s"), *PackagePath);
			return false;
		}
		FAssetRegistryModule::AssetCreated(Made);
	}

	// Each field the source names is found by its name, and kept, so what holds one keeps its
	// value, as when a field is changed in the struct editor. The rest are added, then those the
	// source no longer names are removed, since a struct always has a field, and all are put in
	// the source's order.
	auto Find = [Made](const FString& Name) -> FStructVariableDescription*
	{
		return FStructureEditorUtils::GetVarDesc(Made).FindByPredicate(
			[&Name](const FStructVariableDescription& Var) { return Var.FriendlyName == Name; });
	};
	TArray<FGuid> Wanted;
	for (const TSharedPtr<FJsonValue>& Value : *Fields)
	{
		const TSharedPtr<FJsonObject>& Field = Value->AsObject();
		const FString Name = Field->GetStringField(TEXT("name"));
		FEdGraphPinType Type;
		if (!ParseType(Field->GetStringField(TEXT("type")), Type, OutError))
		{
			return false;
		}
		FGuid Guid;
		if (FStructVariableDescription* Existing = Find(Name))
		{
			Guid = Existing->VarGuid;
			if (Existing->ToPinType() != Type && !FStructureEditorUtils::ChangeVariableType(Made, Guid, Type))
			{
				OutError = FString::Printf(TEXT("could not make %s's field %s a %s"), *AssetName, *Name, *Field->GetStringField(TEXT("type")));
				return false;
			}
		}
		else
		{
			if (!FStructureEditorUtils::AddVariable(Made, Type))
			{
				OutError = FString::Printf(TEXT("%s cannot have a field %s of type %s"), *AssetName, *Name, *Field->GetStringField(TEXT("type")));
				return false;
			}
			Guid = FStructureEditorUtils::GetVarDesc(Made).Last().VarGuid;
			if (!FStructureEditorUtils::RenameVariable(Made, Guid, Name))
			{
				OutError = FString::Printf(TEXT("could not name %s's field %s"), *AssetName, *Name);
				return false;
			}
		}
		FString Default;
		Field->TryGetStringField(TEXT("default"), Default);
		if (FStructureEditorUtils::GetVarDescByGuid(Made, Guid)->DefaultValue != Default
			&& !FStructureEditorUtils::ChangeVariableDefaultValue(Made, Guid, Default))
		{
			OutError = FString::Printf(TEXT("%s is not a default for %s's field %s"), *Default, *AssetName, *Name);
			return false;
		}
		FString Tooltip;
		Field->TryGetStringField(TEXT("description"), Tooltip);
		FStructureEditorUtils::ChangeVariableTooltip(Made, Guid, Tooltip);
		Wanted.Add(Guid);
	}
	for (const FStructVariableDescription& Var : TArray<FStructVariableDescription>(FStructureEditorUtils::GetVarDesc(Made)))
	{
		if (!Wanted.Contains(Var.VarGuid))
		{
			FStructureEditorUtils::RemoveVariable(Made, Var.VarGuid);
		}
	}
	for (int32 Index = 1; Index < Wanted.Num(); ++Index)
	{
		if (FStructureEditorUtils::GetVarDesc(Made)[Index].VarGuid != Wanted[Index])
		{
			FStructureEditorUtils::MoveVariable(Made, Wanted[Index], Wanted[Index - 1], FStructureEditorUtils::PositionBelow);
		}
	}
	FStructureEditorUtils::ChangeTooltip(Made, Description);
	Made->GetPackage()->GetMetaData().SetValue(Made, GeneratedKey, *Tag);
	if (Made->Status != UDSS_UpToDate)
	{
		OutError = FString::Printf(TEXT("%s did not compile: %s"), *AssetName, *Made->ErrorMessage);
		return false;
	}
	Struct = Made;
	return true;
}

bool FLoomApplier::OpImplement(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	// As the Class Settings panel's Implemented Interfaces adds one, which also makes a graph for
	// each of its functions that returns a value, for a "function" op to fill.
	const FString InterfacePath = Op->GetStringField(TEXT("interface"));
	UClass* Interface = LoadObject<UClass>(nullptr, *InterfacePath);
	if (!Interface || !FKismetEditorUtilities::IsClassABlueprintImplementableInterface(Interface))
	{
		OutError = FString::Printf(TEXT("%s is not an interface a Blueprint can implement"), *InterfacePath);
		return false;
	}
	if (!FBlueprintEditorUtils::ImplementNewInterface(Blueprint, Interface->GetClassPathName()))
	{
		OutError = FString::Printf(TEXT("could not implement %s; the Blueprint may implement it already, or have a graph named as one of its functions"), *InterfacePath);
		return false;
	}
	return true;
}

bool FLoomApplier::OpVariable(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	const FString Name = Op->GetStringField(TEXT("name"));
	FEdGraphPinType Type;
	if (!ParseType(Op->GetStringField(TEXT("type")), Type, OutError))
	{
		return false;
	}
	FString Default;
	Op->TryGetStringField(TEXT("default"), Default);
	if (!FBlueprintEditorUtils::AddMemberVariable(Blueprint, FName(Name), Type, Default))
	{
		OutError = FString::Printf(TEXT("could not add variable %s; the name may collide with an inherited member"), *Name);
		return false;
	}
	// A new variable is editable on the class's defaults only. An editable one is shown on each
	// instance too, such as a component added to another Blueprint.
	bool bEditable = false;
	Op->TryGetBoolField(TEXT("editable"), bEditable);
	FBlueprintEditorUtils::SetBlueprintOnlyEditableFlag(Blueprint, FName(Name), !bEditable);
	// A private one only this Blueprint can read or set, as the Details panel's Private box does.
	bool bPrivate = false;
	Op->TryGetBoolField(TEXT("private"), bPrivate);
	if (bPrivate)
	{
		FBlueprintEditorUtils::SetBlueprintVariableMetaData(Blueprint, FName(Name), nullptr, FBlueprintMetadata::MD_Private, TEXT("true"));
	}
	Describe(FName(Name), Op);
	return true;
}

void FLoomApplier::Describe(const FName Member, const TSharedRef<FJsonObject>& Op)
{
	FString Description;
	if (Op->TryGetStringField(TEXT("description"), Description))
	{
		FBlueprintEditorUtils::SetBlueprintVariableMetaData(Blueprint, Member, nullptr, FBlueprintMetadata::MD_Tooltip, Description);
	}
	FString Category;
	if (Op->TryGetStringField(TEXT("category"), Category))
	{
		FBlueprintEditorUtils::SetBlueprintVariableCategory(Blueprint, Member, nullptr, FText::FromString(Category));
	}
}

bool FLoomApplier::OpComponent(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	// As "+ Add" in the Components panel does, with the template's fields set as in Details.
	const FString Name = Op->GetStringField(TEXT("name"));
	const FString ClassPath = Op->GetStringField(TEXT("class"));
	UClass* Class = LoadObject<UClass>(nullptr, *ClassPath);
	if (!Class || !Class->IsChildOf<UActorComponent>())
	{
		OutError = FString::Printf(TEXT("%s is not a component class"), *ClassPath);
		return false;
	}
	USimpleConstructionScript* Construction = Blueprint->SimpleConstructionScript;
	if (!Construction)
	{
		OutError = TEXT("only an actor's Blueprint has components");
		return false;
	}
	USCS_Node* Node = Construction->CreateNode(Class, FName(Name));
	Construction->AddNode(Node);
	if (!SetFieldsFromText(Node->ComponentTemplate, Class, Op, Name, OutError))
	{
		return false;
	}
	FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Blueprint);
	return true;
}

bool FLoomApplier::OpDispatcher(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	// As the editor's "Add Event Dispatcher" does: a multicast delegate variable, and a graph of
	// the same name whose entry node carries the signature.
	const FName Name(Op->GetStringField(TEXT("name")));
	FEdGraphPinType Type;
	Type.PinCategory = UEdGraphSchema_K2::PC_MCDelegate;
	if (!FBlueprintEditorUtils::AddMemberVariable(Blueprint, Name, Type))
	{
		OutError = FString::Printf(TEXT("could not add dispatcher %s; the name may collide with an inherited member"), *Name.ToString());
		return false;
	}
	UEdGraph* Graph = FBlueprintEditorUtils::CreateNewGraph(Blueprint, Name, UEdGraph::StaticClass(), UEdGraphSchema_K2::StaticClass());
	Graph->bEditable = false;
	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();
	Schema->CreateDefaultNodesForGraph(*Graph);
	Schema->CreateFunctionGraphTerminators(*Graph, (UClass*)nullptr);
	Schema->AddExtraFunctionFlags(Graph, FUNC_BlueprintCallable | FUNC_BlueprintEvent | FUNC_Public);
	Schema->MarkFunctionEntryAsEditable(Graph, true);
	Blueprint->DelegateSignatureGraphs.Add(Graph);

	UK2Node_FunctionEntry* Entry = nullptr;
	for (UEdGraphNode* Node : Graph->Nodes)
	{
		if ((Entry = Cast<UK2Node_FunctionEntry>(Node)) != nullptr)
		{
			break;
		}
	}
	if (!Entry)
	{
		OutError = FString::Printf(TEXT("dispatcher %s has no entry node"), *Name.ToString());
		return false;
	}
	const TArray<TSharedPtr<FJsonValue>>* Params = nullptr;
	if (Op->TryGetArrayField(TEXT("params"), Params))
	{
		for (const TSharedPtr<FJsonValue>& Value : *Params)
		{
			const TSharedPtr<FJsonObject> Param = Value->AsObject();
			FEdGraphPinType ParamType;
			if (!ParseType(Param->GetStringField(TEXT("type")), ParamType, OutError))
			{
				return false;
			}
			const FName PinName(Param->GetStringField(TEXT("name")));
			UEdGraphPin* Pin = Entry->CreateUserDefinedPin(PinName, ParamType, EGPD_Output, false);
			if (!Pin || Pin->PinName != PinName)
			{
				OutError = FString::Printf(TEXT("could not add parameter %s to %s"), *PinName.ToString(), *Name.ToString());
				return false;
			}
		}
	}
	Describe(Name, Op);
	FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Blueprint);
	return true;
}

bool FLoomApplier::OpWidget(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	UWidgetBlueprint* WidgetBlueprint = Cast<UWidgetBlueprint>(Blueprint);
	if (!WidgetBlueprint)
	{
		OutError = TEXT("only a widget Blueprint has widgets");
		return false;
	}
	UWidgetTree* Tree = WidgetBlueprint->WidgetTree;
	const FString Name = Op->GetStringField(TEXT("name"));
	const FString ClassPath = Op->GetStringField(TEXT("class"));
	UClass* Class = LoadObject<UClass>(nullptr, *ClassPath);
	if (!Class || !Class->IsChildOf<UWidget>())
	{
		OutError = FString::Printf(TEXT("%s is not a widget class"), *ClassPath);
		return false;
	}

	// Where it goes: into its parent, onto the root canvas, or in place of the canvas as the root.
	FString ParentName;
	const TArray<TSharedPtr<FJsonValue>>* Place = nullptr;
	const bool bHasParent = Op->TryGetStringField(TEXT("parent"), ParentName);
	const bool bPlaced = Op->TryGetArrayField(TEXT("place"), Place) && Place->Num() == 4;
	UPanelWidget* Parent = nullptr;
	if (bHasParent)
	{
		UWidget* Found = Tree->FindWidget(FName(ParentName));
		Parent = Cast<UPanelWidget>(Found);
		if (!Parent)
		{
			OutError = Found
				? FString::Printf(TEXT("%s is a %s, which holds no widgets"), *ParentName, *Found->GetClass()->GetName())
				: FString::Printf(TEXT("no widget %s to hold %s"), *ParentName, *Name);
			return false;
		}
		if (!Parent->CanAddMoreChildren())
		{
			OutError = FString::Printf(TEXT("%s holds one widget, and already has one"), *ParentName);
			return false;
		}
	}
	UCanvasPanel* Canvas = Cast<UCanvasPanel>(Tree->RootWidget);
	if (!bHasParent && !Canvas)
	{
		OutError = TEXT("the tree has a root other than its canvas, and a root is the only widget outside the others");
		return false;
	}

	// No place: the widget is the tree's root, in place of the canvas. The canvas leaves the
	// package first, so the next build can make another of its name.
	const bool bRoot = !bHasParent && !bPlaced;
	if (bRoot)
	{
		WidgetBlueprint->OnVariableRemoved(Canvas->GetFName());
		Tree->RemoveWidget(Canvas);
		Canvas->Rename(nullptr, GetTransientPackage(), REN_DontCreateRedirectors);
	}
	UWidget* Widget = Tree->ConstructWidget<UWidget>(Class, FName(Name));
	Widget->bIsVariable = true;
	if (!SetFieldsFromText(Widget, Class, Op, Name, OutError))
	{
		return false;
	}
	UPanelSlot* Slot = nullptr;
	if (Parent)
	{
		Slot = Parent->AddChild(Widget);
	}
	else if (bPlaced)
	{
		UCanvasPanelSlot* CanvasSlot = Canvas->AddChildToCanvas(Widget);
		CanvasSlot->SetPosition(FVector2D((*Place)[0]->AsNumber(), (*Place)[1]->AsNumber()));
		CanvasSlot->SetSize(FVector2D((*Place)[2]->AsNumber(), (*Place)[3]->AsNumber()));
		Slot = CanvasSlot;
	}
	else
	{
		Tree->RootWidget = Widget;
	}
	if (Op->HasField(TEXT("slot")))
	{
		if (!Slot)
		{
			OutError = FString::Printf(TEXT("%s is the tree's root, which no slot holds"), *Name);
			return false;
		}
		if (!SetFieldsFromText(Slot, Slot->GetClass(), Op, Name + TEXT("'s slot"), OutError, TEXT("slot")))
		{
			return false;
		}
	}
	WidgetBlueprint->OnVariableAdded(Widget->GetFName());
	FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Blueprint);
	return true;
}

bool FLoomApplier::OpFunction(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	const FString Name = Op->GetStringField(TEXT("name"));
	// An override takes its signature, parameters and outputs both, from the class that declares
	// the event.
	FString OverridesPath;
	UClass* Overrides = nullptr;
	if (Op->TryGetStringField(TEXT("overrides"), OverridesPath))
	{
		Overrides = LoadObject<UClass>(nullptr, *OverridesPath);
		if (!Overrides || !Overrides->FindFunctionByName(FName(Name)))
		{
			OutError = FString::Printf(TEXT("%s has no function %s to override"), *OverridesPath, *Name);
			return false;
		}
	}
	// A function of an interface this Blueprint implements has its graph already, made with the
	// interface and not yet filled. One of an interface its parent implements has none.
	UEdGraph* Graph = Overrides && Overrides->HasAnyClassFlags(CLASS_Interface) ? FindInterfaceGraph(Name) : nullptr;
	if (Graph)
	{
		if (FilledInterfaceGraphs.Contains(Graph))
		{
			OutError = FString::Printf(TEXT("graph %s is filled twice"), *Name);
			return false;
		}
		FilledInterfaceGraphs.Add(Graph);
	}
	else if (FindGraph(Name))
	{
		OutError = FString::Printf(TEXT("graph %s already exists"), *Name);
		return false;
	}
	else
	{
		Graph = FBlueprintEditorUtils::CreateNewGraph(Blueprint, FName(Name), UEdGraph::StaticClass(), UEdGraphSchema_K2::StaticClass());
		FBlueprintEditorUtils::AddFunctionGraph<UClass>(Blueprint, Graph, !Overrides, Overrides);
	}
	if (Overrides)
	{
		OverrideGraphs.Add(Graph);
	}

	UK2Node_FunctionEntry* Entry = nullptr;
	for (UEdGraphNode* Node : Graph->Nodes)
	{
		if ((Entry = Cast<UK2Node_FunctionEntry>(Node)) != nullptr)
		{
			break;
		}
	}
	if (!Entry)
	{
		OutError = FString::Printf(TEXT("function %s has no entry node"), *Name);
		return false;
	}
	// What the editor shows for the function: its tooltip, and where the palette lists it.
	FString Description;
	if (Op->TryGetStringField(TEXT("description"), Description))
	{
		Entry->MetaData.ToolTip = FText::FromString(Description);
	}
	FString Category;
	if (Op->TryGetStringField(TEXT("category"), Category))
	{
		Entry->MetaData.Category = FText::FromString(Category);
	}
	// As the Details panel's Pure and Access Specifier set them.
	bool bPure = false;
	if (Op->TryGetBoolField(TEXT("pure"), bPure) && bPure)
	{
		Entry->AddExtraFlags(FUNC_BlueprintPure);
	}
	FString Access;
	if (Op->TryGetStringField(TEXT("access"), Access))
	{
		if (Access != TEXT("private") && Access != TEXT("protected"))
		{
			OutError = FString::Printf(TEXT("%s's access is %s, not private or protected"), *Name, *Access);
			return false;
		}
		Entry->SetExtraFlags((Entry->GetExtraFlags() & ~FUNC_AccessSpecifiers) | (Access == TEXT("private") ? FUNC_Private : FUNC_Protected));
	}

	const TArray<TSharedPtr<FJsonValue>>* Params = nullptr;
	if (!Overrides && Op->TryGetArrayField(TEXT("params"), Params))
	{
		for (const TSharedPtr<FJsonValue>& Value : *Params)
		{
			const TSharedPtr<FJsonObject> Param = Value->AsObject();
			FEdGraphPinType Type;
			if (!ParseType(Param->GetStringField(TEXT("type")), Type, OutError))
			{
				return false;
			}
			bool bByRef = false;
			Param->TryGetBoolField(TEXT("by_ref"), bByRef);
			Type.bIsReference = bByRef;
			const FName PinName(Param->GetStringField(TEXT("name")));
			UEdGraphPin* Pin = Entry->CreateUserDefinedPin(PinName, Type, EGPD_Output, false);
			if (!Pin || Pin->PinName != PinName)
			{
				OutError = FString::Printf(TEXT("could not add parameter %s to %s"), *PinName.ToString(), *Name);
				return false;
			}
			// A default, which a call that leaves the parameter out gives it, as the Details panel
			// sets one on the function's input.
			FString Default;
			if (Param->TryGetStringField(TEXT("default"), Default))
			{
				const TSharedPtr<FUserPinInfo>* Info = Entry->UserDefinedPins.FindByPredicate(
					[&PinName](const TSharedPtr<FUserPinInfo>& P) { return P->PinName == PinName; });
				if (!Info || !Entry->ModifyUserDefinedPinDefaultValue(*Info, Default))
				{
					OutError = FString::Printf(TEXT("%s is not a default for %s's parameter %s"), *Default, *Name, *PinName.ToString());
					return false;
				}
			}
		}
	}
	const TArray<TSharedPtr<FJsonValue>>* Returns = nullptr;
	if (Overrides)
	{
		// The signature made the result node already, if the event returns anything, and wired
		// the entry to it. The ops say what runs, so the wire goes.
		for (UEdGraphNode* Node : Graph->Nodes)
		{
			if (UK2Node_FunctionResult* Result = Cast<UK2Node_FunctionResult>(Node))
			{
				Result->FindPinChecked(UEdGraphSchema_K2::PN_Execute)->BreakAllPinLinks();
				UnclaimedResults.Add(Graph, Result);
			}
		}
	}
	else if (Op->TryGetArrayField(TEXT("returns"), Returns) && Returns->Num() > 0)
	{
		// The function's outputs live on its result nodes. The first is made here, so the
		// signature is known to callers before any body that returns has been built.
		TArray<TPair<FName, FEdGraphPinType>>& Outputs = ReturnPins.Add(Graph);
		for (const TSharedPtr<FJsonValue>& Value : *Returns)
		{
			const TSharedPtr<FJsonObject> Return = Value->AsObject();
			FEdGraphPinType Type;
			if (!ParseType(Return->GetStringField(TEXT("type")), Type, OutError))
			{
				return false;
			}
			Outputs.Emplace(FName(Return->GetStringField(TEXT("name"))), Type);
		}
		UK2Node_FunctionResult* Result = MakeResultNode(Graph, OutError);
		if (!Result)
		{
			return false;
		}
		UnclaimedResults.Add(Graph, Result);
	}
	const TArray<TSharedPtr<FJsonValue>>* Locals = nullptr;
	if (Op->TryGetArrayField(TEXT("locals"), Locals))
	{
		for (const TSharedPtr<FJsonValue>& Value : *Locals)
		{
			const TSharedPtr<FJsonObject> Local = Value->AsObject();
			FEdGraphPinType Type;
			if (!ParseType(Local->GetStringField(TEXT("type")), Type, OutError))
			{
				return false;
			}
			FString Default;
			Local->TryGetStringField(TEXT("default"), Default);
			const FString LocalName = Local->GetStringField(TEXT("name"));
			if (!FBlueprintEditorUtils::AddLocalVariable(Blueprint, Graph, FName(LocalName), Type, Default))
			{
				OutError = FString::Printf(TEXT("could not add local %s to %s"), *LocalName, *Name);
				return false;
			}
		}
	}
	FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Blueprint);
	return true;
}

bool FLoomApplier::OpNode(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	const FString Id = Op->GetStringField(TEXT("id"));
	const FString Kind = Op->GetStringField(TEXT("kind"));
	const FString GraphName = Op->GetStringField(TEXT("graph"));
	if (Nodes.Contains(Id))
	{
		OutError = FString::Printf(TEXT("node id %s is used twice"), *Id);
		return false;
	}
	UEdGraph* Graph = FindGraph(GraphName);
	if (!Graph)
	{
		OutError = FString::Printf(TEXT("no graph %s"), *GraphName);
		return false;
	}

	UEdGraphNode* Node = nullptr;
	if (Kind == TEXT("entry"))
	{
		for (UEdGraphNode* Candidate : Graph->Nodes)
		{
			if (Candidate->IsA<UK2Node_FunctionEntry>())
			{
				Node = Candidate;
			}
		}
		if (!Node)
		{
			OutError = FString::Printf(TEXT("graph %s has no entry node"), *GraphName);
			return false;
		}
		Nodes.Add(Id, Node);
		return true;
	}

	if (Kind == TEXT("event"))
	{
		UClass* Class = LoadObject<UClass>(nullptr, *Op->GetStringField(TEXT("class")));
		const FName Event(Op->GetStringField(TEXT("event")));
		if (!Class || !Class->FindFunctionByName(Event))
		{
			OutError = FString::Printf(TEXT("no event %s on %s"), *Event.ToString(), *Op->GetStringField(TEXT("class")));
			return false;
		}
		FGraphNodeCreator<UK2Node_Event> Creator(*Graph);
		UK2Node_Event* Created = Creator.CreateNode(false);
		Created->EventReference.SetExternalMember(Event, Class);
		Created->bOverrideFunction = true;
		Creator.Finalize();
		Node = Created;
	}
	else if (Kind == TEXT("custom_event"))
	{
		// As the editor's "Add Custom Event" does, with an output pin for each parameter.
		const FString EventName = Op->GetStringField(TEXT("name"));
		FGraphNodeCreator<UK2Node_CustomEvent> Creator(*Graph);
		UK2Node_CustomEvent* Created = Creator.CreateNode(false);
		Created->CustomFunctionName = FName(EventName);
		Creator.Finalize();
		const TArray<TSharedPtr<FJsonValue>>* Params = nullptr;
		if (Op->TryGetArrayField(TEXT("params"), Params))
		{
			for (const TSharedPtr<FJsonValue>& Value : *Params)
			{
				const TSharedPtr<FJsonObject> Param = Value->AsObject();
				FEdGraphPinType Type;
				if (!ParseType(Param->GetStringField(TEXT("type")), Type, OutError))
				{
					return false;
				}
				const FName PinName(Param->GetStringField(TEXT("name")));
				UEdGraphPin* Pin = Created->CreateUserDefinedPin(PinName, Type, EGPD_Output, false);
				if (!Pin || Pin->PinName != PinName)
				{
					OutError = FString::Printf(TEXT("could not add parameter %s to the event %s"), *PinName.ToString(), *EventName);
					return false;
				}
			}
		}
		Node = Created;
	}
	else if (Kind == TEXT("call"))
	{
		const FString Function = Op->GetStringField(TEXT("function"));
		FString Owner, FunctionName;
		if (!Function.Split(TEXT(":"), &Owner, &FunctionName))
		{
			OutError = FString::Printf(TEXT("function must be <class path>:<name> or self:<name>, not %s"), *Function);
			return false;
		}
		UFunction* Found = nullptr;
		if (Owner != TEXT("self"))
		{
			UClass* Class = LoadObject<UClass>(nullptr, *Owner);
			Found = Class ? Class->FindFunctionByName(FName(FunctionName)) : nullptr;
			if (!Found)
			{
				OutError = FString::Printf(TEXT("no function %s"), *Function);
				return false;
			}
		}
		// The array library's functions take arrays of any type, which only their own node
		// resolves from what is linked to them.
		const bool bArray = Found && Found->HasMetaData(TEXT("ArrayParm"));
		FGraphNodeCreator<UK2Node_CallFunction> Creator(*Graph);
		UK2Node_CallFunction* Created = bArray
			? Creator.CreateNode(false, UK2Node_CallArrayFunction::StaticClass())
			: Creator.CreateNode(false);
		if (Found)
		{
			Created->SetFromFunction(Found);
		}
		else
		{
			Created->FunctionReference.SetSelfMember(FName(FunctionName));
		}
		Creator.Finalize();
		Node = Created;
	}
	else if (Kind == TEXT("message"))
	{
		// As the editor's "(Message)" call: on an object of any class, doing nothing when it does
		// not implement the interface.
		const FString Function = Op->GetStringField(TEXT("function"));
		FString Owner, FunctionName;
		Function.Split(TEXT(":"), &Owner, &FunctionName);
		UClass* Interface = LoadObject<UClass>(nullptr, *Owner);
		UFunction* Found = Interface && Interface->HasAnyClassFlags(CLASS_Interface) ? Interface->FindFunctionByName(FName(FunctionName)) : nullptr;
		if (!Found)
		{
			OutError = FString::Printf(TEXT("no interface function %s"), *Function);
			return false;
		}
		FGraphNodeCreator<UK2Node_CallFunction> Creator(*Graph);
		UK2Node_CallFunction* Created = Creator.CreateNode(false, UK2Node_Message::StaticClass());
		Created->SetFromFunction(Found);
		Creator.Finalize();
		Node = Created;
	}
	else if (Kind == TEXT("call_parent"))
	{
		// As "Add call to parent function" makes: the version the parent class runs, which may be
		// a Blueprint parent's override of an event its own parent declares.
		const FString Function = Op->GetStringField(TEXT("function"));
		FString Owner, FunctionName;
		Function.Split(TEXT(":"), &Owner, &FunctionName);
		UFunction* Found = Blueprint->ParentClass ? Blueprint->ParentClass->FindFunctionByName(FName(FunctionName)) : nullptr;
		if (!Found)
		{
			OutError = FString::Printf(TEXT("the parent class has no function %s"), *FunctionName);
			return false;
		}
		FGraphNodeCreator<UK2Node_CallParentFunction> Creator(*Graph);
		UK2Node_CallParentFunction* Created = Creator.CreateNode(false);
		Created->SetFromFunction(Found);
		Creator.Finalize();
		Node = Created;
	}
	else if (Kind == TEXT("result"))
	{
		UK2Node_FunctionResult* Result = nullptr;
		if (!UnclaimedResults.RemoveAndCopyValue(Graph, Result))
		{
			Result = MakeResultNode(Graph, OutError);
			if (!Result)
			{
				return false;
			}
		}
		Node = Result;
	}
	else if (Kind == TEXT("break"))
	{
		const FString StructPath = Op->GetStringField(TEXT("struct"));
		UScriptStruct* StructType = LoadObject<UScriptStruct>(nullptr, *StructPath);
		if (!StructType)
		{
			OutError = FString::Printf(TEXT("no struct %s"), *StructPath);
			return false;
		}
		FGraphNodeCreator<UK2Node_BreakStruct> Creator(*Graph);
		UK2Node_BreakStruct* Created = Creator.CreateNode(false);
		Created->StructType = StructType;
		Creator.Finalize();
		Node = Created;
	}
	else if (Kind == TEXT("make"))
	{
		const FString StructPath = Op->GetStringField(TEXT("struct"));
		UScriptStruct* StructType = LoadObject<UScriptStruct>(nullptr, *StructPath);
		if (!StructType)
		{
			OutError = FString::Printf(TEXT("no struct %s"), *StructPath);
			return false;
		}
		FGraphNodeCreator<UK2Node_MakeStruct> Creator(*Graph);
		UK2Node_MakeStruct* Created = Creator.CreateNode(false);
		Created->StructType = StructType;
		Creator.Finalize();
		Node = Created;
	}
	else if (Kind == TEXT("enum_equal"))
	{
		const FString EnumPath = Op->GetStringField(TEXT("enum"));
		UEnum* EnumType = LoadObject<UEnum>(nullptr, *EnumPath);
		if (!EnumType)
		{
			OutError = FString::Printf(TEXT("no enum %s"), *EnumPath);
			return false;
		}
		FGraphNodeCreator<UK2Node_EnumEquality> Creator(*Graph);
		UK2Node_EnumEquality* Created = Creator.CreateNode(false);
		Creator.Finalize();
		// Typed now rather than by whatever is linked, which may not have its type yet when a
		// value written out is set on the other pin.
		for (UEdGraphPin* Input : {Created->GetInput1Pin(), Created->GetInput2Pin()})
		{
			Input->PinType.PinCategory = UEdGraphSchema_K2::PC_Byte;
			Input->PinType.PinSubCategoryObject = EnumType;
		}
		Node = Created;
	}
	else if (Kind == TEXT("enum_literal"))
	{
		const FString EnumPath = Op->GetStringField(TEXT("enum"));
		UEnum* EnumType = LoadObject<UEnum>(nullptr, *EnumPath);
		if (!EnumType)
		{
			OutError = FString::Printf(TEXT("no enum %s"), *EnumPath);
			return false;
		}
		FGraphNodeCreator<UK2Node_EnumLiteral> Creator(*Graph);
		UK2Node_EnumLiteral* Created = Creator.CreateNode(false);
		Created->Enum = EnumType;
		Creator.Finalize();
		Node = Created;
	}
	else if (Kind == TEXT("byte_to_enum"))
	{
		// Unchecked, so a value the enum does not name comes through as it is.
		const FString EnumPath = Op->GetStringField(TEXT("enum"));
		UEnum* EnumType = LoadObject<UEnum>(nullptr, *EnumPath);
		if (!EnumType)
		{
			OutError = FString::Printf(TEXT("no enum %s"), *EnumPath);
			return false;
		}
		FGraphNodeCreator<UK2Node_CastByteToEnum> Creator(*Graph);
		UK2Node_CastByteToEnum* Created = Creator.CreateNode(false);
		Created->Enum = EnumType;
		Created->bSafe = false;
		Creator.Finalize();
		Node = Created;
	}
	else if (Kind == TEXT("set_fields"))
	{
		const FString StructPath = Op->GetStringField(TEXT("struct"));
		UScriptStruct* StructType = LoadObject<UScriptStruct>(nullptr, *StructPath);
		if (!StructType)
		{
			OutError = FString::Printf(TEXT("no struct %s"), *StructPath);
			return false;
		}
		FGraphNodeCreator<UK2Node_SetFieldsInStruct> Creator(*Graph);
		UK2Node_SetFieldsInStruct* Created = Creator.CreateNode(false);
		Created->StructType = StructType;
		Creator.Finalize();
		// The node starts with every field's pin hidden; show the ones being set.
		for (const TSharedPtr<FJsonValue>& Field : Op->GetArrayField(TEXT("fields")))
		{
			FOptionalPinFromProperty* Shown = Created->ShowPinForProperties.FindByPredicate(
				[&](const FOptionalPinFromProperty& P) { return P.PropertyName == FieldName(StructType, Field->AsString()); });
			if (!Shown)
			{
				OutError = FString::Printf(TEXT("%s has no field %s"), *StructPath, *Field->AsString());
				return false;
			}
			Shown->bShowPin = true;
		}
		Created->ReconstructNode();
		Node = Created;
	}
	else if (Kind == TEXT("cast") || Kind == TEXT("class_cast"))
	{
		const FString ClassPath = Op->GetStringField(TEXT("class"));
		UClass* Class = LoadObject<UClass>(nullptr, *ClassPath);
		if (!Class)
		{
			OutError = FString::Printf(TEXT("no class %s"), *ClassPath);
			return false;
		}
		FGraphNodeCreator<UK2Node_DynamicCast> Creator(*Graph);
		UK2Node_DynamicCast* Created = Kind == TEXT("cast")
			? Creator.CreateNode(false)
			: Creator.CreateNode(false, UK2Node_ClassDynamicCast::StaticClass());
		Created->TargetType = Class;
		Creator.Finalize();
		Created->SetPurity(true);
		Node = Created;
	}
	else if (Kind == TEXT("subsystem"))
	{
		const FString ClassPath = Op->GetStringField(TEXT("class"));
		UClass* Class = LoadObject<UClass>(nullptr, *ClassPath);
		// The node classes are not exported, so they are found by name.
		UClass* NodeClass = !Class ? nullptr : FindObject<UClass>(nullptr, Class->IsChildOf<UEngineSubsystem>()
			? TEXT("/Script/BlueprintGraph.K2Node_GetEngineSubsystem")
			: TEXT("/Script/BlueprintGraph.K2Node_GetEditorSubsystem"));
		if (!NodeClass)
		{
			OutError = FString::Printf(TEXT("cannot get the subsystem %s"), *ClassPath);
			return false;
		}
		FGraphNodeCreator<UK2Node_GetSubsystem> Creator(*Graph);
		UK2Node_GetSubsystem* Created = Creator.CreateNode(false, NodeClass);
		Created->Initialize(Class);
		Creator.Finalize();
		Node = Created;
	}
	else if (Kind == TEXT("bound_event"))
	{
		// Made as the component's green + in the Details panel makes it, without the editor's
		// jump to the new node, which needs a window.
		const FName Component(Op->GetStringField(TEXT("component")));
		const FName Dispatcher(Op->GetStringField(TEXT("dispatcher")));
		FObjectProperty* Property = FindFProperty<FObjectProperty>(Blueprint->SkeletonGeneratedClass, Component);
		FMulticastDelegateProperty* Delegate = Property ? FindFProperty<FMulticastDelegateProperty>(Property->PropertyClass, Dispatcher) : nullptr;
		if (!Delegate)
		{
			OutError = FString::Printf(TEXT("no component %s with a dispatcher %s"), *Component.ToString(), *Dispatcher.ToString());
			return false;
		}
		FGraphNodeCreator<UK2Node_ComponentBoundEvent> Creator(*Graph);
		UK2Node_ComponentBoundEvent* Created = Creator.CreateNode(false);
		Created->InitializeComponentBoundEventParams(Property, Delegate);
		Creator.Finalize();
		Node = Created;
	}
	else if (Kind == TEXT("delegate"))
	{
		// Create Event. It takes its signature from the pin its output is linked to, and forgets
		// its function whenever a link changes while it has none that fits, so the function is
		// set once every link is made, when the Blueprint is compiled.
		FGraphNodeCreator<UK2Node_CreateDelegate> Creator(*Graph);
		UK2Node_CreateDelegate* Created = Creator.CreateNode(false);
		Creator.Finalize();
		PendingDelegates.Emplace(Created, FName(Op->GetStringField(TEXT("function"))));
		Node = Created;
	}
	else if (Kind == TEXT("add_delegate") || Kind == TEXT("remove_delegate") || Kind == TEXT("clear_delegate"))
	{
		// Bind Event, Unbind Event and Unbind all Events, of a class's dispatcher or, with no
		// class, of this Blueprint's own, on this object. This Blueprint's class, named, is its
		// skeleton until it is compiled.
		FString ClassPath;
		const bool bSelf = !Op->TryGetStringField(TEXT("class"), ClassPath);
		const FName Dispatcher(Op->GetStringField(TEXT("dispatcher")));
		UClass* Own = Blueprint->GeneratedClass;
		UClass* Class = bSelf || (Own && Own->GetPathName() == ClassPath)
			? Blueprint->SkeletonGeneratedClass.Get() : LoadObject<UClass>(nullptr, *ClassPath);
		FMulticastDelegateProperty* Delegate = Class ? FindFProperty<FMulticastDelegateProperty>(Class, Dispatcher) : nullptr;
		if (!Delegate)
		{
			OutError = FString::Printf(TEXT("%s has no dispatcher %s"), bSelf ? *Blueprint->GetName() : *ClassPath, *Dispatcher.ToString());
			return false;
		}
		UClass* NodeClass = Kind == TEXT("add_delegate") ? UK2Node_AddDelegate::StaticClass()
			: Kind == TEXT("remove_delegate") ? UK2Node_RemoveDelegate::StaticClass()
			: UK2Node_ClearDelegate::StaticClass();
		FGraphNodeCreator<UK2Node_BaseMCDelegate> Creator(*Graph);
		UK2Node_BaseMCDelegate* Created = Creator.CreateNode(false, NodeClass);
		Created->SetFromProperty(Delegate, bSelf, Class);
		Creator.Finalize();
		Node = Created;
	}
	else if (Kind == TEXT("broadcast"))
	{
		const FName Dispatcher(Op->GetStringField(TEXT("dispatcher")));
		const FGuid Guid = FBlueprintEditorUtils::FindMemberVariableGuidByName(Blueprint, Dispatcher);
		if (!Guid.IsValid())
		{
			OutError = FString::Printf(TEXT("no dispatcher %s"), *Dispatcher.ToString());
			return false;
		}
		FGraphNodeCreator<UK2Node_CallDelegate> Creator(*Graph);
		UK2Node_CallDelegate* Created = Creator.CreateNode(false);
		Created->DelegateReference.SetSelfMember(Dispatcher, Guid);
		Creator.Finalize();
		if (!Created->GetDelegateSignature())
		{
			OutError = FString::Printf(TEXT("dispatcher %s has no signature yet"), *Dispatcher.ToString());
			return false;
		}
		Node = Created;
	}
	else if (Kind == TEXT("self"))
	{
		FGraphNodeCreator<UK2Node_Self> Creator(*Graph);
		Node = Creator.CreateNode(false);
		Creator.Finalize();
	}
	else if (Kind == TEXT("array_get"))
	{
		FGraphNodeCreator<UK2Node_GetArrayItem> Creator(*Graph);
		Node = Creator.CreateNode(false);
		Creator.Finalize();
	}
	else if (Kind == TEXT("create_widget"))
	{
		const FString ClassPath = Op->GetStringField(TEXT("class"));
		UClass* Class = LoadObject<UClass>(nullptr, *ClassPath);
		// The node's class lives in a private header of the UMG editor, so it is found by name.
		UClass* NodeClass = FindObject<UClass>(nullptr, TEXT("/Script/UMGEditor.K2Node_CreateWidget"));
		if (!Class || !NodeClass)
		{
			OutError = FString::Printf(TEXT("cannot create a widget of %s"), *ClassPath);
			return false;
		}
		FGraphNodeCreator<UK2Node_ConstructObjectFromClass> Creator(*Graph);
		UK2Node_ConstructObjectFromClass* Created = Creator.CreateNode(false, NodeClass);
		Creator.Finalize();
		UEdGraphPin* ClassPin = Created->GetClassPin();
		ClassPin->DefaultObject = Class;
		// Retypes the output to the class, as picking it in the editor does.
		Created->PinDefaultValueChanged(ClassPin);
		Node = Created;
	}
	else if (Kind == TEXT("construct"))
	{
		const FString ClassPath = Op->GetStringField(TEXT("class"));
		UClass* Class = LoadObject<UClass>(nullptr, *ClassPath);
		if (!Class)
		{
			OutError = FString::Printf(TEXT("cannot construct %s"), *ClassPath);
			return false;
		}
		FGraphNodeCreator<UK2Node_GenericCreateObject> Creator(*Graph);
		UK2Node_GenericCreateObject* Created = Creator.CreateNode(false);
		Creator.Finalize();
		UEdGraphPin* ClassPin = Created->GetClassPin();
		ClassPin->DefaultObject = Class;
		// Retypes the output to the class, as picking it in the editor does.
		Created->PinDefaultValueChanged(ClassPin);
		Node = Created;
	}
	else if (Kind == TEXT("branch"))
	{
		FGraphNodeCreator<UK2Node_IfThenElse> Creator(*Graph);
		Node = Creator.CreateNode(false);
		Creator.Finalize();
	}
	else if (Kind == TEXT("get") || Kind == TEXT("set"))
	{
		const FName Var(Op->GetStringField(TEXT("var")));
		const FString Scope = Op->GetStringField(TEXT("scope"));
		FMemberReference Reference;
		if (Scope == TEXT("self"))
		{
			FGuid Guid = FBlueprintEditorUtils::FindMemberVariableGuidByName(Blueprint, Var);
			if (const UWidgetBlueprint* WidgetBlueprint = Cast<UWidgetBlueprint>(Blueprint); !Guid.IsValid() && WidgetBlueprint)
			{
				// A widget in the tree is a variable too, but not one of the Blueprint's own.
				Guid = WidgetBlueprint->WidgetVariableNameToGuidMap.FindRef(Var);
			}
			// So is a component in the Components tree.
			if (const USCS_Node* Component = Blueprint->SimpleConstructionScript ? Blueprint->SimpleConstructionScript->FindSCSNode(Var) : nullptr; !Guid.IsValid() && Component)
			{
				Guid = Component->VariableGuid;
			}
			if (!Guid.IsValid())
			{
				OutError = FString::Printf(TEXT("no member variable %s"), *Var.ToString());
				return false;
			}
			Reference.SetSelfMember(Var, Guid);
		}
		else if (Scope == TEXT("external") || Scope == TEXT("inherited"))
		{
			const FString ClassPath = Op->GetStringField(TEXT("class"));
			UClass* Class = LoadObject<UClass>(nullptr, *ClassPath);
			FProperty* Property = Class ? FindFProperty<FProperty>(Class, Var) : nullptr;
			if (!Property)
			{
				OutError = FString::Printf(TEXT("%s has no property %s"), *ClassPath, *Var.ToString());
				return false;
			}
			// An external variable belongs to another object, which is linked to the node's
			// "self" pin. An inherited one is read on this object, and the node has no such pin.
			Reference.SetFromField<FProperty>(Property, Scope == TEXT("inherited"));
		}
		else if (Scope == TEXT("local"))
		{
			const FBPVariableDescription* Local = FBlueprintEditorUtils::FindLocalVariable(Blueprint, Graph, Var);
			if (!Local)
			{
				OutError = FString::Printf(TEXT("no local %s in %s"), *Var.ToString(), *GraphName);
				return false;
			}
			Reference.SetLocalMember(Var, GraphName, Local->VarGuid);
		}
		else
		{
			OutError = FString::Printf(TEXT("scope must be self, local, external or inherited, not %s"), *Scope);
			return false;
		}
		if (Kind == TEXT("get"))
		{
			FGraphNodeCreator<UK2Node_VariableGet> Creator(*Graph);
			UK2Node_VariableGet* Created = Creator.CreateNode(false);
			Created->VariableReference = Reference;
			Creator.Finalize();
			Node = Created;
		}
		else
		{
			FGraphNodeCreator<UK2Node_VariableSet> Creator(*Graph);
			UK2Node_VariableSet* Created = Creator.CreateNode(false);
			Created->VariableReference = Reference;
			Creator.Finalize();
			Node = Created;
		}
	}
	else
	{
		OutError = FString::Printf(TEXT("unknown node kind '%s'"), *Kind);
		return false;
	}

	Nodes.Add(Id, Node);
	return true;
}

UEdGraphPin* FLoomApplier::FindPin(const FString& Ref, FString& OutError) const
{
	FString Id, PinName;
	if (!Ref.Split(TEXT("."), &Id, &PinName))
	{
		OutError = FString::Printf(TEXT("pin reference must be <node id>.<pin>, not %s"), *Ref);
		return nullptr;
	}
	UEdGraphNode* const* Node = Nodes.Find(Id);
	if (!Node)
	{
		OutError = FString::Printf(TEXT("no node %s"), *Id);
		return nullptr;
	}
	UEdGraphPin* Pin = (*Node)->FindPin(FName(PinName));
	// A cast names its output after its class, and a subsystem node its output as it likes, so
	// ops.json calls them "Result" and "ReturnValue".
	if (const UK2Node_DynamicCast* CastNode = Cast<UK2Node_DynamicCast>(*Node); !Pin && CastNode && PinName == TEXT("Result"))
	{
		Pin = CastNode->GetCastResultPin();
	}
	if (const UK2Node_GetSubsystem* Subsystem = Cast<UK2Node_GetSubsystem>(*Node); !Pin && Subsystem && PinName == TEXT("ReturnValue"))
	{
		Pin = Subsystem->GetResultPin();
	}
	// A field of a user-defined struct, on a node that makes, breaks or sets one.
	if (const UK2Node_StructOperation* StructNode = Cast<UK2Node_StructOperation>(*Node); !Pin && StructNode)
	{
		Pin = (*Node)->FindPin(FieldName(StructNode->StructType, PinName));
	}
	if (!Pin)
	{
		OutError = FString::Printf(TEXT("node %s has no pin %s; it has: %s"), *Id, *PinName, *DescribePins(*Node));
	}
	return Pin;
}

bool FLoomApplier::OpLink(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	UEdGraphPin* From = FindPin(Op->GetStringField(TEXT("from")), OutError);
	if (!From)
	{
		return false;
	}
	UEdGraphPin* To = FindPin(Op->GetStringField(TEXT("to")), OutError);
	if (!To)
	{
		return false;
	}
	// Only a plain connection is accepted. Anything the schema would add or break on the side is
	// a mistake in the ops, and the compiler should have said what it meant.
	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();
	const FPinConnectionResponse Response = Schema->CanCreateConnection(From, To);
	if (Response.Response != CONNECT_RESPONSE_MAKE)
	{
		OutError = FString::Printf(TEXT("cannot link %s to %s: %s (%s)"), *Op->GetStringField(TEXT("from")),
			*Op->GetStringField(TEXT("to")), *ResponseName(Response.Response), *Response.Message.ToString());
		return false;
	}
	if (!Schema->TryCreateConnection(From, To))
	{
		OutError = FString::Printf(TEXT("linking %s to %s failed"), *Op->GetStringField(TEXT("from")),
			*Op->GetStringField(TEXT("to")));
		return false;
	}
	return true;
}

bool FLoomApplier::OpDefault(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	UEdGraphPin* Pin = FindPin(Op->GetStringField(TEXT("pin")), OutError);
	if (!Pin)
	{
		return false;
	}
	const FString Value = Op->GetStringField(TEXT("value"));
	// An object or a class is given to its pin loaded, as the editor's asset picker gives it. A
	// Blueprint of another asset is not loaded until something asks for it.
	const FName Category = Pin->PinType.PinCategory;
	UObject* Loaded = nullptr;
	if ((Category == UEdGraphSchema_K2::PC_Object || Category == UEdGraphSchema_K2::PC_Class) && Value.StartsWith(TEXT("/")))
	{
		Loaded = LoadObject<UObject>(nullptr, *Value);
		if (!Loaded)
		{
			OutError = FString::Printf(TEXT("default on %s: nothing loads at %s"), *Op->GetStringField(TEXT("pin")), *Value);
			return false;
		}
	}
	if (Loaded)
	{
		GetDefault<UEdGraphSchema_K2>()->TrySetDefaultObject(*Pin, Loaded);
	}
	else
	{
		GetDefault<UEdGraphSchema_K2>()->TrySetDefaultValue(*Pin, Value);
	}
	const FString Held = Pin->GetDefaultAsString();
	if (Held != Value)
	{
		const FString Why = GetDefault<UEdGraphSchema_K2>()->IsPinDefaultValid(Pin, Loaded ? FString() : Value, Loaded, FText());
		OutError = FString::Printf(TEXT("default on %s: set '%s', pin holds '%s'%s%s"), *Op->GetStringField(TEXT("pin")),
			*Value, *Held, Why.IsEmpty() ? TEXT("") : TEXT(": "), *Why);
		return false;
	}
	return true;
}

bool FLoomApplier::OpCompile(FString& OutError)
{
	// Every link is made by now, so each Create Event can be given its function, which it checks
	// against the signature of what it feeds.
	for (const TPair<UK2Node_CreateDelegate*, FName>& Pending : PendingDelegates)
	{
		if (!Pending.Key->GetDelegateOutPin()->LinkedTo.Num())
		{
			OutError = FString::Printf(TEXT("the delegate to %s feeds nothing, so it has no signature"), *Pending.Value.ToString());
			return false;
		}
		Pending.Key->SetFunction(Pending.Value);
		Pending.Key->HandleAnyChangeWithoutNotifying();
	}
	PendingDelegates.Empty();

	// Every node and link is made by now, so each graph can be laid out as a whole.
	TArray<UEdGraph*> Graphs(Blueprint->UbergraphPages);
	Graphs.Append(Blueprint->FunctionGraphs);
	for (UEdGraph* Graph : Graphs)
	{
		FLoomLayout::Arrange(Graph);
		if (!FLoomLayout::CheckNoOverlap(Graph, OutError))
		{
			OutError = TEXT("the layout overlaps nodes: ") + OutError;
			return false;
		}
	}

	FCompilerResultsLog Results;
	Results.SetSourcePath(Blueprint->GetPathName());
	FKismetEditorUtilities::CompileBlueprint(Blueprint, EBlueprintCompileOptions::SkipGarbageCollection, &Results);

	TArray<TSharedPtr<FJsonValue>> Messages;
	for (const TSharedRef<FTokenizedMessage>& Message : Results.Messages)
	{
		Messages.Add(MakeShared<FJsonValueString>(Message->ToText().ToString()));
	}
	TSharedRef<FJsonObject> Compile = MakeShared<FJsonObject>();
	Compile->SetStringField(TEXT("status"), StatusName(Blueprint->Status));
	Compile->SetNumberField(TEXT("errors"), Results.NumErrors);
	Compile->SetNumberField(TEXT("warnings"), Results.NumWarnings);
	Compile->SetArrayField(TEXT("messages"), Messages);
	Report->SetObjectField(TEXT("compile"), Compile);

	// Warnings count as failure: in generated code a warning is a compiler bug.
	bCompiledClean = Blueprint->Status == BS_UpToDate && Results.NumErrors == 0 && Results.NumWarnings == 0;
	if (!bCompiledClean)
	{
		OutError = FString::Printf(TEXT("compile finished %s with %d errors and %d warnings"),
			*StatusName(Blueprint->Status), Results.NumErrors, Results.NumWarnings);
	}
	return bCompiledClean;
}

namespace
{
	/**
	 * The value of a property, or of a field inside one ("a.b"), in an object: the property and
	 * where its value lies.
	 */
	bool FindValue(UObject* Object, const FString& Path, const FProperty*& OutProperty, void*& OutValue, FString& OutError)
	{
		TArray<FString> Names;
		Path.ParseIntoArray(Names, TEXT("."));
		const UStruct* Struct = Object->GetClass();
		void* Container = Object;
		for (int32 Index = 0; Index < Names.Num(); ++Index)
		{
			const FProperty* Property = FindFProperty<FProperty>(Struct, FName(Names[Index]));
			if (!Property)
			{
				OutError = FString::Printf(TEXT("%s has no %s"), *Struct->GetName(), *Names[Index]);
				return false;
			}
			void* Value = Property->ContainerPtrToValuePtr<void>(Container);
			if (Index == Names.Num() - 1)
			{
				OutProperty = Property;
				OutValue = Value;
				return true;
			}
			const FStructProperty* Inner = CastField<FStructProperty>(Property);
			if (!Inner)
			{
				OutError = FString::Printf(TEXT("%s is not a struct, so it has no %s"), *Names[Index], *Names[Index + 1]);
				return false;
			}
			Struct = Inner->Struct;
			Container = Value;
		}
		OutError = TEXT("an empty property path");
		return false;
	}
}

bool FLoomApplier::OpClassDefault(const TSharedRef<FJsonObject>& Op, FString& OutError)
{
	// As the Class Defaults panel sets a value: on the class the compile made.
	UObject* Defaults = Blueprint->GeneratedClass ? Blueprint->GeneratedClass->GetDefaultObject() : nullptr;
	if (!Defaults)
	{
		OutError = TEXT("the Blueprint has no compiled class to give defaults to");
		return false;
	}
	const FString Name = Op->GetStringField(TEXT("name"));
	const FProperty* Property = nullptr;
	void* Value = nullptr;
	if (!FindValue(Defaults, Name, Property, Value, OutError))
	{
		return false;
	}
	FString Text;
	FString FromPath;
	if (Op->TryGetStringField(TEXT("from"), FromPath))
	{
		// Another class's default for the same property, copied whole through its text.
		UClass* From = LoadObject<UClass>(nullptr, *FromPath);
		if (!From)
		{
			OutError = FString::Printf(TEXT("no class %s to copy %s from"), *FromPath, *Name);
			return false;
		}
		const FProperty* FromProperty = nullptr;
		void* FromValue = nullptr;
		if (!FindValue(From->GetDefaultObject(), Name, FromProperty, FromValue, OutError))
		{
			return false;
		}
		if (!FromProperty->SameType(Property))
		{
			OutError = FString::Printf(TEXT("%s is not the same type in %s"), *Name, *From->GetName());
			return false;
		}
		FromProperty->ExportTextItem_Direct(Text, FromValue, nullptr, From->GetDefaultObject(), PPF_None);
	}
	else if (!Op->TryGetStringField(TEXT("value"), Text))
	{
		OutError = FString::Printf(TEXT("class_default %s has no value"), *Name);
		return false;
	}
	Defaults->Modify();
	// What the Class Defaults panel does around an edit, named by the property the path starts at.
	TArray<FString> Names;
	Name.ParseIntoArray(Names, TEXT("."));
	FProperty* Outer = FindFProperty<FProperty>(Defaults->GetClass(), FName(Names[0]));
	Defaults->PreEditChange(Outer);
	// A string or a text written out is taken whole, as for a component's fields: text import
	// would stop at its first dot.
	const bool bWritten = !Op->HasField(TEXT("from"));
	if (const FStrProperty* String = CastField<FStrProperty>(Property); String && bWritten)
	{
		String->SetPropertyValue(Value, Text);
	}
	else if (const FTextProperty* TextProperty = CastField<FTextProperty>(Property); TextProperty && bWritten)
	{
		TextProperty->SetPropertyValue(Value, FText::AsCultureInvariant(Text));
	}
	else if (!Property->ImportText_Direct(*Text, Value, Defaults, PPF_None))
	{
		OutError = FString::Printf(TEXT("%s is not a value for %s"), *Text.Left(200), *Name);
		return false;
	}
	FPropertyChangedEvent Changed(Outer, EPropertyChangeType::ValueSet);
	Defaults->PostEditChangeProperty(Changed);
	FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
	return true;
}

bool FLoomApplier::OpSave(FString& OutError)
{
	if (UObject* Asset = Enum ? static_cast<UObject*>(Enum) : Struct)
	{
		if (!BuildRecord.IsEmpty())
		{
			Asset->GetPackage()->GetMetaData().SetValue(Asset, TEXT("LoomBuild"), *BuildRecord);
		}
		FString File;
		if (!SaveAsset(Asset, File, OutError))
		{
			return false;
		}
		Report->SetStringField(TEXT("saved"), File);
		return true;
	}
	if (!bCompiledClean)
	{
		OutError = TEXT("refusing to save a Blueprint that has not compiled cleanly");
		return false;
	}
	if (!BuildRecord.IsEmpty())
	{
		Blueprint->GetPackage()->GetMetaData().SetValue(Blueprint, TEXT("LoomBuild"), *BuildRecord);
	}
	FString File;
	if (!SaveAsset(Blueprint, File, OutError))
	{
		return false;
	}
	Report->SetStringField(TEXT("saved"), File);
	return true;
}

FString FLoomApplier::ReadBuildRecord(const UObject* Asset)
{
	const FString* Record = Asset->GetPackage()->GetMetaData().FindValue(Asset, TEXT("LoomBuild"));
	return Record ? *Record : FString();
}

bool FLoomApplier::SaveAsset(UObject* Asset, FString& OutFile, FString& OutError)
{
	UPackage* Package = Asset->GetOutermost();
	Package->MarkPackageDirty();
	const FString File = FPackageName::LongPackageNameToFilename(Package->GetName(), FPackageName::GetAssetPackageExtension());
	FSavePackageArgs Args;
	Args.TopLevelFlags = RF_Public | RF_Standalone;
	Args.SaveFlags = SAVE_NoError;
	if (!UPackage::SavePackage(Package, Asset, *File, Args))
	{
		OutError = FString::Printf(TEXT("saving %s failed"), *File);
		return false;
	}
	OutFile = FPaths::ConvertRelativePathToFull(File);
	return true;
}

UK2Node_FunctionResult* FLoomApplier::MakeResultNode(UEdGraph* Graph, FString& OutError)
{
	FGraphNodeCreator<UK2Node_FunctionResult> Creator(*Graph);
	UK2Node_FunctionResult* Result = Creator.CreateNode(false);
	if (OverrideGraphs.Contains(Graph))
	{
		// Its outputs come from the overridden function, as the entry node's parameters do.
		for (UEdGraphNode* Node : Graph->Nodes)
		{
			if (const UK2Node_FunctionEntry* Entry = Cast<UK2Node_FunctionEntry>(Node))
			{
				Result->FunctionReference = Entry->FunctionReference;
			}
		}
	}
	Creator.Finalize();
	// A later result node may already have copied the outputs from the first.
	for (const TPair<FName, FEdGraphPinType>& Output : ReturnPins.FindRef(Graph))
	{
		if (!Result->FindPin(Output.Key, EGPD_Input) && !Result->CreateUserDefinedPin(Output.Key, Output.Value, EGPD_Input, false))
		{
			OutError = FString::Printf(TEXT("could not add output %s to %s"), *Output.Key.ToString(), *Graph->GetName());
			return nullptr;
		}
	}
	FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Blueprint);
	return Result;
}

UEdGraph* FLoomApplier::FindGraph(const FString& Name) const
{
	if (Name == TEXT("EventGraph"))
	{
		return FBlueprintEditorUtils::FindEventGraph(Blueprint);
	}
	for (UEdGraph* Graph : Blueprint->FunctionGraphs)
	{
		if (Graph->GetName() == Name)
		{
			return Graph;
		}
	}
	return FindInterfaceGraph(Name);
}

UEdGraph* FLoomApplier::FindInterfaceGraph(const FString& Name) const
{
	for (const FBPInterfaceDescription& Interface : Blueprint->ImplementedInterfaces)
	{
		for (UEdGraph* Graph : Interface.Graphs)
		{
			if (Graph->GetName() == Name)
			{
				return Graph;
			}
		}
	}
	return nullptr;
}

void FLoomApplier::ExportGraphs()
{
	if (!Blueprint)
	{
		return;
	}
	TSharedRef<FJsonObject> Graphs = MakeShared<FJsonObject>();
	TArray<UEdGraph*> All(Blueprint->UbergraphPages);
	All.Append(Blueprint->FunctionGraphs);
	for (const FBPInterfaceDescription& Interface : Blueprint->ImplementedInterfaces)
	{
		All.Append(Interface.Graphs);
	}
	for (UEdGraph* Graph : All)
	{
		TSet<UObject*> Export;
		for (UEdGraphNode* Node : Graph->Nodes)
		{
			Export.Add(Node);
		}
		FString Text;
		FEdGraphUtilities::ExportNodesToText(Export, Text);
		Graphs->SetStringField(Graph->GetName(), Text);
	}
	Report->SetObjectField(TEXT("graphs"), Graphs);
}
