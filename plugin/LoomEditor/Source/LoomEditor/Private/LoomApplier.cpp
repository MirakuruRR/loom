	const TCHAR* GeneratedKey = TEXT("LoomGenerated");

	/**
	 * The name a struct's field has on nodes, from the name ops.json gives it: a user-defined struct
	 * stores a field under a generated name, and finds it by the one the editor shows.
	 */
	FName FieldName(const UScriptStruct* Struct, const FString& Named)
	{
		if (!Struct)
		{
			return FName(Named);
		}
		const FProperty* Field = Struct->FindPropertyByName(FName(Named));
		if (!Field)
		{
			Field = Struct->CustomFindProperty(FName(Named));
		}
		return Field ? Field->GetFName() : FName(Named);
	}

	bool ParseType(const FString& Spec, FEdGraphPinType& Out, FString& OutError)
	{
		if (Spec.StartsWith(TEXT("array<")) && Spec.EndsWith(TEXT(">")))
		{
			if (!ParseType(Spec.Mid(6, Spec.Len() - 7), Out, OutError))
			{
				return false;
			}
			Out.ContainerType = EPinContainerType::Array;
			return true;
		}
		if (Spec.StartsWith(TEXT("set<")) && Spec.EndsWith(TEXT(">")))
		{
			if (!ParseType(Spec.Mid(4, Spec.Len() - 5), Out, OutError))
			{
				return false;
			}
			Out.ContainerType = EPinContainerType::Set;
			return true;
		}
		if (Spec.StartsWith(TEXT("map<")) && Spec.EndsWith(TEXT(">")))
		{
			// The key and value are split at the one comma outside angle brackets.
			const FString Inner = Spec.Mid(4, Spec.Len() - 5);
			int32 Depth = 0;
			int32 Comma = INDEX_NONE;
			for (int32 i = 0; i < Inner.Len() && Comma == INDEX_NONE; ++i)
			{
				const TCHAR C = Inner[i];
				Depth += C == TEXT('<') ? 1 : C == TEXT('>') ? -1 : 0;
				if (C == TEXT(',') && Depth == 0)
				{
					Comma = i;
				}
			}
			FEdGraphPinType Value;
			if (Comma == INDEX_NONE)
			{
				OutError = FString::Printf(TEXT("a map type is map<key,value>, not %s"), *Spec);
				return false;
			}
			if (!ParseType(Inner.Left(Comma), Out, OutError) || !ParseType(Inner.Mid(Comma + 1), Value, OutError))
			{
				return false;
			}
			Out.ContainerType = EPinContainerType::Map;
			Out.PinValueType = FEdGraphTerminalType::FromPinType(Value);
			return true;
		}
		Out = FEdGraphPinType();
		if (Spec == TEXT("bool")) { Out.PinCategory = UEdGraphSchema_K2::PC_Boolean; return true; }
		if (Spec == TEXT("int")) { Out.PinCategory = UEdGraphSchema_K2::PC_Int; return true; }
		if (Spec == TEXT("int64")) { Out.PinCategory = UEdGraphSchema_K2::PC_Int64; return true; }
		if (Spec == TEXT("float"))
		{
			Out.PinCategory = UEdGraphSchema_K2::PC_Real;
			Out.PinSubCategory = UEdGraphSchema_K2::PC_Double;
			return true;
		}
		// A 32-bit float, as the editor makes a function to bind to an engine delegate that passes one.
		if (Spec == TEXT("float32"))
		{
			Out.PinCategory = UEdGraphSchema_K2::PC_Real;
			Out.PinSubCategory = UEdGraphSchema_K2::PC_Float;
			return true;
		}
		if (Spec == TEXT("string")) { Out.PinCategory = UEdGraphSchema_K2::PC_String; return true; }
		if (Spec == TEXT("name")) { Out.PinCategory = UEdGraphSchema_K2::PC_Name; return true; }
		if (Spec == TEXT("text")) { Out.PinCategory = UEdGraphSchema_K2::PC_Text; return true; }
		FString Kind, Path;
		static const TMap<FString, FName> ClassKinds = {
			{TEXT("object"), UEdGraphSchema_K2::PC_Object},
			{TEXT("class"), UEdGraphSchema_K2::PC_Class},
			{TEXT("softobject"), UEdGraphSchema_K2::PC_SoftObject},
			{TEXT("softclass"), UEdGraphSchema_K2::PC_SoftClass},
			{TEXT("interface"), UEdGraphSchema_K2::PC_Interface},
		};
		if (Spec.Split(TEXT(":"), &Kind, &Path) && ClassKinds.Contains(Kind))
		{
			UClass* Class = LoadObject<UClass>(nullptr, *Path);
			if (!Class)
			{
				OutError = FString::Printf(TEXT("no class %s"), *Path);
				return false;
			}
			Out.PinCategory = ClassKinds[Kind];
			Out.PinSubCategoryObject = Class;
			return true;
		}
		if (Kind == TEXT("struct"))
		{
			UScriptStruct* Struct = LoadObject<UScriptStruct>(nullptr, *Path);
			if (!Struct)
			{
				OutError = FString::Printf(TEXT("no struct %s"), *Path);
				return false;
			}
			Out.PinCategory = UEdGraphSchema_K2::PC_Struct;
			Out.PinSubCategoryObject = Struct;
			return true;
		}
		if (Kind == TEXT("delegate"))
		{
			// A single-cast delegate, named by its signature, as a pin dragged from one carries it.
			UFunction* Signature = LoadObject<UFunction>(nullptr, *Path);
			if (!Signature)
			{
				OutError = FString::Printf(TEXT("no delegate signature %s"), *Path);
				return false;
			}
			Out.PinCategory = UEdGraphSchema_K2::PC_Delegate;
			FMemberReference::FillSimpleMemberReference<UFunction>(Signature, Out.PinSubCategoryMemberReference);
			return true;
		}
		if (Kind == TEXT("enum"))
		{
			UEnum* Enum = LoadObject<UEnum>(nullptr, *Path);
			if (!Enum)
			{
				OutError = FString::Printf(TEXT("no enum %s"), *Path);
				return false;
			}
			Out.PinCategory = UEdGraphSchema_K2::PC_Byte;
			Out.PinSubCategoryObject = Enum;
			return true;
		}
		OutError = FString::Printf(TEXT("unknown type '%s'"), *Spec);
		return false;
	}

	/** Sets each of an op's "fields", or the fields under Key, on Target, an object of Class, from text as the Details panel does. */
	bool SetFieldsFromText(UObject* Target, UClass* Class, const TSharedRef<FJsonObject>& Op, const FString& Owner, FString& OutError,
		const TCHAR* Key = TEXT("fields"))
	{
		const TArray<TSharedPtr<FJsonValue>>* Fields = nullptr;
		if (!Op->TryGetArrayField(Key, Fields))
		{
			return true;
		}
		for (const TSharedPtr<FJsonValue>& Value : *Fields)
		{
			const TSharedPtr<FJsonObject> Field = Value->AsObject();
			const FString FieldName = Field->GetStringField(TEXT("name"));
			const FString Text = Field->GetStringField(TEXT("value"));
			FProperty* Property = FindFProperty<FProperty>(Class, FName(FieldName));
			if (!Property)
			{
				OutError = FString::Printf(TEXT("%s has no %s"), *GetPathNameSafe(Class), *FieldName);
				return false;
			}
			// Around the change, what the Details panel does around an edit, so the object hears
			// of it, as a static mesh component must of its mesh.
			Target->PreEditChange(Property);
			// A string or a text is taken whole: text import would stop at its first dot.
			if (const FStrProperty* String = CastField<FStrProperty>(Property))
			{
				String->SetPropertyValue_InContainer(Target, Text);
			}
			else if (const FTextProperty* TextProperty = CastField<FTextProperty>(Property))
			{
				TextProperty->SetPropertyValue_InContainer(Target, FText::AsCultureInvariant(Text));
			}
			else if (!Property->ImportText_InContainer(*Text, Target, Target, PPF_None))
			{
				OutError = FString::Printf(TEXT("%s is not a value for %s.%s"), *Text, *Owner, *FieldName);
				return false;
			}
			FPropertyChangedEvent Changed(Property, EPropertyChangeType::ValueSet);
			Target->PostEditChangeProperty(Changed);
		}
		return true;
	}

	FString DescribePins(const UEdGraphNode* Node)
	{
		TArray<FString> Parts;
		for (const UEdGraphPin* Pin : Node->Pins)
		{
			Parts.Add(FString::Printf(TEXT("%s (%s %s)"), *Pin->PinName.ToString(),
				Pin->Direction == EGPD_Input ? TEXT("in") : TEXT("out"), *Pin->PinType.PinCategory.ToString()));
		}
		return FString::Join(Parts, TEXT(", "));
	}

	FString ResponseName(ECanCreateConnectionResponse Response)
	{
		switch (Response)
		{
		case CONNECT_RESPONSE_MAKE: return TEXT("make");
		case CONNECT_RESPONSE_DISALLOW: return TEXT("disallowed");
		case CONNECT_RESPONSE_BREAK_OTHERS_A: return TEXT("would break the source's other links");
		case CONNECT_RESPONSE_BREAK_OTHERS_B: return TEXT("would break the target's other links");
		case CONNECT_RESPONSE_BREAK_OTHERS_AB: return TEXT("would break both pins' other links");
		case CONNECT_RESPONSE_MAKE_WITH_CONVERSION_NODE: return TEXT("needs a conversion node");
		case CONNECT_RESPONSE_MAKE_WITH_PROMOTION: return TEXT("needs a type promotion");
		default: return TEXT("unknown response");
		}
	}

	FString StatusName(EBlueprintStatus Status)
	{
		switch (Status)
		{
		case BS_Unknown: return TEXT("unknown");
		case BS_Dirty: return TEXT("dirty");
		case BS_Error: return TEXT("error");
		case BS_UpToDate: return TEXT("up_to_date");
		case BS_BeingCreated: return TEXT("being_created");
		case BS_UpToDateWithWarnings: return TEXT("up_to_date_with_warnings");
		default: return TEXT("unknown");
		}
	}
